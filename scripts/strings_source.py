import os, re, subprocess, sys
from xml.sax.saxutils import escape
def esc(v):
    v = escape(v).replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if v.startswith("@") or v.startswith("?"): v = "\\" + v
    return v
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app/src/main/res")
for idx, path in ((0, "values/strings.xml"), (1, "values-en/strings.xml")):
    with open(os.path.join(RES, path), "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n')
        for k in sorted(S):
            attrs = ' translatable="false"' if k == "app_name" else ""
            if idx == 1 and k == "app_name": continue
            f.write(f'    <string name="{k}"{attrs}>{esc(S[k][idx])}</string>\n')
        f.write('</resources>\n')
src = os.path.join(ROOT, "app/src/main")
used = set(re.findall(r"R\.string\.([a-z_0-9]+)", subprocess.run(["grep", "-rhoE", r"R\.string\.[a-z_0-9]+", os.path.join(src, "kotlin")], capture_output=True, text=True).stdout))
used |= set(re.findall(r"@string/([a-z_0-9]+)", subprocess.run(["grep", "-rhoE", r"@string/[a-z_0-9]+", os.path.join(src, "res"), os.path.join(src, "AndroidManifest.xml")], capture_output=True, text=True).stdout))
print("missing:", used - set(S)); print("unused:", set(S) - used)
